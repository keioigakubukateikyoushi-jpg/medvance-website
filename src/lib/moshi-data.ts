export function getGapComment(currentBand: Band, target: TargetType): string {
  const bands: Band[] = ['E', 'D', 'C', 'B', 'A', 'S'];
  const gap = bands.indexOf(TARGET_INFO[target].minBand) - bands.indexOf(currentBand);
  const t = TARGET_INFO[target].label;
  if (gap <= 0) return `現時点で${t}の合格ラインを満たしています。安定感を高め、弱点を精度よく潰す段階です。`;
  if (gap === 1) return `${t}の合格ラインまであと1段階です。弱点科目の集中的な底上げで十分届く射程内です。`;
  if (gap === 2) return `${t}の合格ラインまで2段階の強化が必要です。学年と残り時間を考慮した現実的な戦略が重要です。`;
  return `${t}の合格ラインまで相当の差があります。正直に言えば現時点では厳しい状況ですが、正しい戦略と指導があれば逆転は十分可能です。`;
}

