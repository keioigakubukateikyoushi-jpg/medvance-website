export function getBand(n: number): Band {
  if (n >= 70) return 'S';
  if (n >= 65) return 'A';
  if (n >= 60) return 'B';
  if (n >= 55) return 'C';
  if (n >= 50) return 'D';
  return 'E';
}

export function normalize(score: number, examType: ExamType): number {
  return Math.round((score + EXAM_INFO[examType].offset) * 10) / 10;
}

