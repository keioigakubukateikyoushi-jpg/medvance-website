import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = path.join(ROOT, "content/academy");

function u(id, chapter, title, minutes, goal, prereq, points, defName, defBody, steps, exA, ansA, exB, ansB, drill, drillAns, traps) {
  return { id, chapter, title, minutes, goal, prereq, points, defName, defBody, steps, exA, ansA, exB, ansB, drill, drillAns, traps };
}

function lessonMd(subjectLabel, unit, nextId) {
  const points = unit.points.map((p) => `- ${p}`).join("\n");
  const steps = unit.steps.map((s, i) => `${i + 1}. ${s}`).join("\n");
  const traps = unit.traps.map((t) => `- ${t}`).join("\n");
  const prereq = unit.prereq.length ? unit.prereq.join(", ") : "なし";
  return `# ${unit.id} ${unit.title}

- ブランド: **Medvance**（医学部・難関大受験）
- 科目: ${subjectLabel}
- 章: ${unit.chapter}
- 目安: **${unit.minutes}分**
- 前提: ${prereq}
- 次: ${nextId || "（章末）"}

## 今日のゴール
${unit.goal}

## 受験での位置づけ
学科で差がつかない局面ほど、面接・小論文が合否を分ける。ここは「落とす理由」を消す準備の単元。

## 前提チェック
${unit.prereq.length ? unit.prereq.map((p) => `- ${p}`).join("\n") : "- 入口ユニット（ここから開始可）"}

## この回のポイント
${points}

## 定義・用語
### ${unit.defName}
${unit.defBody}

## 核となる手順
${steps}

## 例題A（標準）
${unit.exA}

### 解答A
- ${unit.ansA}

## 例題B（受験）
${unit.exB}

### 解答B
- ${unit.ansB}

## 演習
${unit.drill}

### 解答
${unit.drillAns}

## 落とし穴（減点パターン）
${traps}

## 到達チェック
- ゴールを何も見ずに言える
- 例題を自分の言葉で再現できる
- 落とし穴を説明できる

## 次へ
${nextId ? `\`${nextId}\`` : "章内の到達チェックを満たしてから次章へ。"}

---
© Medvance · 無断転載禁止
`;
}

function storyboardMd(unit) {
  return `# 台本 ${unit.id}\n\n12ブロック: ゴール→位置づけ→前提→ポイント→定義→手順→例A→答A→例B→答B→演習→落とし穴\n本文準拠。特定年の入試問題は創作しない。\n`;
}

function quizJson(unit) {
  return {
    unit_id: unit.id,
    title: unit.title,
    pass_score: 4,
    questions: [
      { id: "q1", type: "short", prompt: "ゴールは？", answer: unit.goal },
      { id: "q2", type: "short", prompt: "例題Aの要点は？", answer: unit.ansA },
      {
        id: "q3",
        type: "mc",
        prompt: "落とし穴として近いものは？",
        choices: [unit.traps[0], "勘で答える", "準備不要と思う", "暗記だけで本番に臨む"],
        answer: unit.traps[0],
      },
      { id: "q4", type: "short", prompt: "手順の第1は？", answer: unit.steps[0] },
      { id: "q5", type: "short", prompt: "演習の答えは？", answer: unit.drillAns },
    ],
  };
}

function writeSubject(dirName, subject, design, chapters, units) {
  const base = path.join(CONTENT, dirName);
  for (const sub of ["lessons", "storyboard", "slides", "quiz"]) {
    fs.mkdirSync(path.join(base, sub), { recursive: true });
  }
  const indexUnits = units.map((unit, i) => {
    const nextId = units[i + 1]?.id;
    fs.writeFileSync(path.join(base, "lessons", `${unit.id}.md`), lessonMd(subject, unit, nextId));
    fs.writeFileSync(path.join(base, "storyboard", `${unit.id}.md`), storyboardMd(unit));
    fs.writeFileSync(
      path.join(base, "slides", `${unit.id}.md`),
      `# スライド ${unit.id}\n\n${unit.points.map((p) => `- ${p}`).join("\n")}\n`,
    );
    fs.writeFileSync(path.join(base, "quiz", `${unit.id}.json`), JSON.stringify(quizJson(unit), null, 2));
    return {
      id: unit.id,
      chapter: unit.chapter,
      title: unit.title,
      minutes: unit.minutes,
      goal: unit.goal,
      prereq: unit.prereq,
      status: "full",
      file: `lessons/${unit.id}.md`,
      storyboard: `storyboard/${unit.id}.md`,
      slides: `slides/${unit.id}.md`,
      quiz: `quiz/${unit.id}.json`,
    };
  });
  const index = {
    subject,
    track: "exam",
    trackLabel: "基礎講座",
    brand: "Medvance",
    unit_count: indexUnits.length,
    full_count: indexUnits.length,
    outline_count: 0,
    design,
    completeness: "医学部面接・小論文の型を原子スキル分割。到達チェック付き。",
    chapters,
    units: indexUnits,
  };
  fs.writeFileSync(path.join(base, "index.json"), JSON.stringify(index, null, 2));
  fs.writeFileSync(path.join(base, "README.md"), `# ${subject}\n\nユニット数: ${indexUnits.length}\n`);
  console.log("wrote", dirName, indexUnits.length);
  return indexUnits.length;
}

