function lesson(spec) {
  const definitionBody = spec.definitions.map((line) => `- ${line}`).join("\n");
  const stepBody = spec.steps.map((line, i) => `${i + 1}. ${line}`).join("\n");
  const exampleBody = spec.example.map((line) => `${line}`).join("\n\n");
  const practiceBody = spec.practice.map((line, i) => `(${i + 1}) ${line}`).join("\n\n");
  const answerBody = spec.answers.map((line, i) => `(${i + 1}) ${line}`).join("\n\n");
  const trapBody = spec.traps.map((line) => `- ${line}`).join("\n");
  return `# ${spec.id} ${spec.title}

- ブランド: Medvance
- 講座: 基礎講座
- 科目: ${spec.subject}
- 章: ${spec.chapter}
- 設計: 1中心技能、5〜9分、NotebookLM生成用

## 今日のゴール

${spec.goal}。定義を言えるだけでなく、条件を読み、途中過程を示し、自分で誤りを検算できる状態を目標とする。このPartでは「${spec.title}」だけを完結させ、別Partの概念を無理に詰め込まない。

## 受験での位置づけ

基礎問題では、用語の意味、条件の読み取り、標準手順の再現が得点の土台になる。複合問題でも、最初に「${spec.title}」を正しく処理できなければ、その後の計算や考察が連鎖的に崩れる。答えだけでなく、どの条件を使い、なぜその操作を選んだかを説明できることが重要である。

## この回のポイント

- 定義に含まれる条件と対象範囲を先に固定する。
- 数値だけでなく、記号・単位・向き・桁を対応させる。
- 標準手順を飛ばさず、途中結果を次の操作へ渡す。
- 最後に別表現または逆操作で結論を検算する。

## 定義・用語

${definitionBody}

表記・単位・正負・対象範囲を省略すると、同じ数値でも意味が変わる。問題文の語句を数学・理科の定義へ翻訳し、必要な条件を答案の最初に固定する。

## 判断の根拠

「${spec.title}」では、見た目が似た選択肢でも定義が要求する条件を満たすかどうかで結論が変わる。まず対象を確定し、使える情報と使えない情報を分ける。その後に操作へ進めば、${spec.traps[0]}という典型誤答を防げる。

また、途中結果には元の問題との対応を残す。どの数値・記号・条件から得た結果なのかを書けば、次の段階で取り違えに気づける。正答した場合も、結論を定義へ戻して説明することで偶然の一致ではないと確認できる。

## 核となる手順

${stepBody}

各段階の結果を次の段階へ渡す前に、定義との一致、単位、符号、桁、重複や漏れを確認する。途中過程を残すと、誤りが起きた位置を特定できる。

## 例題

次の条件を標準手順に沿って整理し、途中過程と結論を示す。

### 解答A

${exampleBody}

最後に、得られた結論が問題の条件と矛盾しないか、別の表現や逆操作で確認する。この検算まで含めて1つの標準解法とする。

## 記述のしかた

答案では、最初に基準・対象・使用する定義を短く書く。次に計算または判定を1段階ずつ示し、各行で何を求めたか分かるようにする。最後は数値だけで終えず、必要な単位・向き・集合・物理的または化学的意味を添える。

途中で複数の場合が生じるときは、場合分けの条件を明記する。結果が同じでも経路が異なる場合は重複の有無を確認し、測定や実験操作では安全性と記録精度を優先する。

## 演習

${practiceBody}

## 演習の解答

${answerBody}

答えが一致しない場合は、計算結果だけを直すのではなく、条件の読み替え、対象の選択、単位・符号、手順の順番へ戻って原因を特定する。

## 落とし穴

${trapBody}

これらの誤りは、定義を曖昧にしたまま数値操作へ進むと起こる。操作前の確認事項を短く書き、結果の意味を日本語で言い直すと防ぎやすい。

## 到達チェック

- ${spec.goal}。
- 例題の手順を見ずに再現し、各行の理由を説明できる。
- 演習3問を解き、誤答した場合に落とし穴のどれに該当するか判断できる。

このPartの到達条件を満たしたら、次Partへ進み、関連する概念との接続を学ぶ。
`;
}

