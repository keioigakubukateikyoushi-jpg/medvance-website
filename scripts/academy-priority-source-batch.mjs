function quiz(spec) {
  const prompts = [
    `${spec.title}の定義・説明として最も適切なものを選んでください。`,
    `${spec.title}を処理するとき、最初に確認すべき事項を選んでください。`,
    `例題の条件から得られる結論として正しいものを選んでください。`,
    `${spec.title}で起こりやすい誤りとして該当するものを選んでください。`,
    `演習(1)の答えとして正しいものを選んでください。`,
    `このPartの到達条件として最も適切なものを選んでください。`,
  ];
  const correct = [
    spec.definitions[0],
    spec.steps[0],
    spec.example.at(-1),
    spec.traps[0],
    spec.answers[0],
    `${spec.goal}こと`,
  ];
  const distractors = [
    ["用語は数値の大小だけで決まり、条件や単位は不要である。", "答えが合えば途中過程は確認しなくてよい。", "別Partの内容を先に適用して判断する。"],
    ["最終結果だけを先に推測する", "単位や符号をすべて消す", "条件を読まず暗記した式を使う"],
    [spec.example[0], spec.practice[0], spec.traps[1]],
    [spec.steps[1], spec.answers[1], spec.definitions[1]],
    [spec.answers[1], spec.answers[2], spec.traps[2]],
    ["用語だけを暗記して適用しないこと", "途中過程を省略して答えだけ書くこと", "誤答原因を確認せず次へ進むこと"],
  ];
  return {
    unit_id: spec.id,
    quality: "reviewed-v3",
    questions: prompts.map((prompt, index) => ({
      prompt,
      choices: [correct[index], ...distractors[index]],
      answer: 0,
      explanation: `正答は「${correct[index]}」。正本の定義・手順・例題に直接対応する。`,
    })),
  };
}

for (const spec of specs) {
  const base = path.join(CONTENT, spec.subject);
  const outputs = {
    [`lessons/${spec.id}.md`]: lesson(spec),
    [`storyboard/${spec.id}.md`]: storyboard(spec),
    [`slides/${spec.id}.md`]: slides(spec),
    [`quiz/${spec.id}.json`]: `${JSON.stringify(quiz(spec), null, 2)}\n`,
  };
  for (const [relative, body] of Object.entries(outputs)) {
    const output = path.join(base, relative);
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, body);
  }
}

