function writeSubject(dirName, subject, design, chapters, units, { merge = false } = {}) {
  const base = path.join(CONTENT, dirName);
  for (const sub of ["lessons", "storyboard", "slides", "quiz"]) {
    fs.mkdirSync(path.join(base, sub), { recursive: true });
  }

  let existing = [];
  const indexPath = path.join(base, "index.json");
  if (merge && fs.existsSync(indexPath)) {
    existing = JSON.parse(fs.readFileSync(indexPath, "utf8")).units || [];
  }
  const existingIds = new Set(existing.map((x) => x.id));
  const allUnitDefs = merge
    ? [
        // keep existing content files; only append new defs
        ...existing.map((e) => ({ __existing: true, ...e })),
        ...units.filter((u) => !existingIds.has(u.id)),
      ]
    : units;

  const indexUnits = [];
  const defsById = Object.fromEntries(units.map((x) => [x.id, x]));

  if (merge) {
    for (const e of existing) {
      indexUnits.push(e);
    }
  }

  for (let i = 0; i < units.length; i++) {
    const unit = units[i];
    if (merge && existingIds.has(unit.id)) continue;
    const next =
      units[i + 1]?.id ||
      null;
    // next might be another new unit; for chain within new batch only
    const nextId = units[i + 1]?.id;
    fs.writeFileSync(path.join(base, "lessons", `${unit.id}.md`), lessonMd(subject, unit, nextId));
    fs.writeFileSync(path.join(base, "storyboard", `${unit.id}.md`), storyboardMd(unit));
    fs.writeFileSync(
      path.join(base, "slides", `${unit.id}.md`),
      `# スライド ${unit.id}\n\n${unit.points.map((p) => `- ${p}`).join("\n")}\n`,
    );
    fs.writeFileSync(path.join(base, "quiz", `${unit.id}.json`), JSON.stringify(quizJson(unit), null, 2));
    indexUnits.push({
      id: unit.id,
      chapter: unit.chapter,
      title: unit.title,
      minutes: unit.minutes,
      goal: unit.goal,
      prereq: unit.prereq,
      status: "full",
      file: `lessons/${unit.id}.md`,
      storyboard: `storyboard/${unit.id}.md`,
      slides: `slides/${unit.id}.md`,
      quiz: `quiz/${unit.id}.json`,
    });
  }

  // unique chapters preserving order
  const chSet = [];
  for (const c of chapters) if (!chSet.includes(c)) chSet.push(c);
  for (const u of indexUnits) if (!chSet.includes(u.chapter)) chSet.push(u.chapter);

  const index = {
    subject,
    track: "exam",
    trackLabel: "基礎講座",
    brand: "Medvance",
    unit_count: indexUnits.length,
    full_count: indexUnits.length,
    outline_count: 0,
    design,
    completeness: "高校課程・受験範囲を原子スキル分割。到達チェック付き。",
    chapters: chSet,
    units: indexUnits,
  };
  fs.writeFileSync(indexPath, JSON.stringify(index, null, 2));
  fs.writeFileSync(path.join(base, "README.md"), `# ${subject}\n\nユニット数: ${indexUnits.length}\n抜けなし設計。\n`);
  console.log(dirName, "→", indexUnits.length, "units", merge ? "(merged)" : "(new)");
  return indexUnits.length;
}

