import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = path.join(ROOT, "content/academy");

function u(id, chapter, title, minutes, goal, prereq, points, defName, defBody, steps, exA, ansA, exB, ansB, drill, drillAns, traps, strategy) {
  return {
    id,
    chapter,
    title,
    minutes,
    goal,
    prereq,
    points,
    defName,
    defBody,
    steps,
    exA,
    ansA,
    exB,
    ansB,
    drill,
    drillAns,
    traps,
    strategy:
      strategy ||
      "共通テストは「知識の暗記」より「資料・本文に根拠があるか」で差がつく。根拠箇所を指差せる状態をゴールにする。",
  };
}

function lessonMd(subjectLabel, unit, nextId) {
  const points = unit.points.map((p) => `- ${p}`).join("\n");
  const steps = unit.steps.map((s, i) => `${i + 1}. ${s}`).join("\n");
  const traps = unit.traps.map((t) => `- ${t}`).join("\n");
  const prereq = unit.prereq.length ? unit.prereq.join(", ") : "なし";
  return `# ${unit.id} ${unit.title}

- ブランド: **Medvance**（医学部・難関大受験）
- 科目: ${subjectLabel}
- 章: ${unit.chapter}
- 目安: **${unit.minutes}分**
- 前提: ${prereq}
- 次: ${nextId || "（章末）"}

## 今日のゴール
${unit.goal}

## 受験での位置づけ
共通テストは時間との勝負であり、**根拠を本文・資料から拾えるか**が得点に直結する。医学部志望でも一次で足切りにならないよう、ここは「速く・正確に」を型で固める。

### 共通テスト攻略の方針
${unit.strategy}

## 前提チェック
${unit.prereq.length ? unit.prereq.map((p) => `- ${p}`).join("\n") : "- 入口ユニット（この回から開始してよい）"}

## この回のポイント
${points}

## 定義・用語
### ${unit.defName}
${unit.defBody}

## 核となる手順（試験でそのまま使う）
${steps}

## 例題A（標準・型の確認）
${unit.exA}

### 解答A
- ${unit.ansA}

## 例題B（共通テスト型・やや実戦）
${unit.exB}

### 解答B
- ${unit.ansB}

## 演習（自力で再現）
${unit.drill}

### 解答
${unit.drillAns}

## 落とし穴（減点・ひっかけパターン）
${traps}

## 到達チェック（完璧の条件）
- ゴールを何も見ずに言える
- 例題A・Bを白紙で手順から再現できる
- 落とし穴を「なぜダメか」まで説明できる
- 次の単元に進む前に、今日の型を1問で使える

## 次へ
${nextId ? `\`${nextId}\`` : "章内の到達チェックをすべて満たしてから次章へ。"}

---
© Medvance · 無断転載禁止
`;
}

function storyboardMd(unit) {
  return `# 台本 ${unit.id}

12ブロック: ゴール→位置づけ→方針→前提→ポイント→定義→手順→例A→答A→例B→答B→演習・落とし穴
本文準拠。創作しない。共通テストの時間感覚（1問あたりの目安）に触れる。
`;
}

function quizJson(unit) {
  return {
    unit_id: unit.id,
    title: unit.title,
    pass_score: 4,
    questions: [
      { id: "q1", type: "short", prompt: "今日のゴールは？", answer: unit.goal },
      { id: "q2", type: "short", prompt: `用語「${unit.defName}」を一文で。`, answer: unit.defBody },
      {
        id: "q3",
        type: "mc",
        prompt: "落とし穴として近いものは？",
        choices: [unit.traps[0], "根拠を本文に戻る", "選択肢を比較する", "設問の条件を読む"],
        answer: unit.traps[0],
      },
      { id: "q4", type: "short", prompt: "手順の第1は？", answer: unit.steps[0] },
      { id: "q5", type: "short", prompt: "演習の答え（要点）は？", answer: unit.drillAns },
    ],
  };
}

function writeSubject(dirName, subject, design, chapters, units) {
  const base = path.join(CONTENT, dirName);
  for (const sub of ["lessons", "storyboard", "slides", "quiz"]) {
    fs.mkdirSync(path.join(base, sub), { recursive: true });
  }

  const indexUnits = [];
  for (let i = 0; i < units.length; i++) {
    const unit = units[i];
    const nextId = units[i + 1]?.id || null;
    fs.writeFileSync(path.join(base, "lessons", `${unit.id}.md`), lessonMd(subject, unit, nextId));
    fs.writeFileSync(path.join(base, "storyboard", `${unit.id}.md`), storyboardMd(unit));
    fs.writeFileSync(
      path.join(base, "slides", `${unit.id}.md`),
      `# スライド ${unit.id}\n\n## ${unit.title}\n\n${unit.points.map((p) => `- ${p}`).join("\n")}\n\n### 手順\n${unit.steps.map((s, n) => `${n + 1}. ${s}`).join("\n")}\n`,
    );
    fs.writeFileSync(path.join(base, "quiz", `${unit.id}.json`), JSON.stringify(quizJson(unit), null, 2));
    indexUnits.push({
      id: unit.id,
      chapter: unit.chapter,
      title: unit.title,
      minutes: unit.minutes,
      goal: unit.goal,
      prereq: unit.prereq,
      status: "full",
      file: `lessons/${unit.id}.md`,
      storyboard: `storyboard/${unit.id}.md`,
      slides: `slides/${unit.id}.md`,
      quiz: `quiz/${unit.id}.json`,
    });
  }

  const index = {
    subject,
    track: "common-test",
    trackLabel: "共通テスト対策",
    brand: "Medvance",
    unit_count: indexUnits.length,
    full_count: indexUnits.length,
    outline_count: 0,
    design,
    completeness: "共通テスト出題範囲を分野別に原子スキル分割。到達チェック付き。",
    chapters,
    units: indexUnits,
  };
  fs.writeFileSync(path.join(base, "index.json"), JSON.stringify(index, null, 2));
  fs.writeFileSync(
    path.join(base, "README.md"),
    `# ${subject}\n\nユニット数: ${indexUnits.length}\n分野: ${chapters.join(" / ")}\n\n共通テストで点が安定する「型」を先に固定する講座。\n`,
  );
  console.log(dirName, "→", indexUnits.length, "units");
  return index;
}

