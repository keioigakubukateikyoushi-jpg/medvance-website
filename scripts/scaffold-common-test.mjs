function updateCatalog(newSubjects) {
  const catalogPath = path.join(CONTENT, "catalog.json");
  const cat = JSON.parse(fs.readFileSync(catalogPath, "utf8"));

  // Ensure track exists
  let commonTrack = cat.tracks.find((t) => t.id === "common-test");
  if (!commonTrack) {
    commonTrack = {
      id: "common-test",
      label: "共通テスト対策",
      description: "国語・社会・情報を分野別に。資料読解と型で一次の足場を固める。",
      subjects: [],
    };
    // insert after foundation
    const fi = cat.tracks.findIndex((t) => t.id === "foundation");
    cat.tracks.splice(fi + 1, 0, commonTrack);
  }

  const upsert = (entry) => {
    const i = commonTrack.subjects.findIndex((s) => s.id === entry.id);
    if (i >= 0) commonTrack.subjects[i] = entry;
    else commonTrack.subjects.push(entry);

    const j = cat.subjects.findIndex((s) => s.id === entry.id);
    if (j >= 0) cat.subjects[j] = entry;
    else {
      // insert before advanced entries
      const adv = cat.subjects.findIndex((s) => s.id.startsWith("advanced/"));
      if (adv >= 0) cat.subjects.splice(adv, 0, entry);
      else cat.subjects.push(entry);
    }
  };

  for (const s of newSubjects) upsert(s);

  // recompute totals roughly
  let all = 0;
  let foundation = 0;
  let common = 0;
  let advanced = 0;
  let elite = 0;
  for (const t of cat.tracks) {
    for (const s of t.subjects) {
      all += s.unit_count || 0;
      if (t.id === "foundation") foundation += s.unit_count || 0;
      if (t.id === "common-test") common += s.unit_count || 0;
      if (t.id === "advanced") advanced += s.unit_count || 0;
      if (t.id === "elite") elite += s.unit_count || 0;
    }
  }
  cat.totals = {
    foundation_units: foundation,
    common_test_units: common,
    advanced_units: advanced,
    elite_units: elite,
    all_units: all,
    all_full: all,
  };
  cat.system = "4-track: foundation / common-test / advanced / elite";
  cat.promise =
    "Medvanceの基礎講座・共通テスト対策を指定順で完了すれば、高校課程と共通テストで必要な範囲を抜けなくマスターできる設計。";

  fs.writeFileSync(catalogPath, JSON.stringify(cat, null, 2));
  console.log("catalog updated. all_units=", all, "common_test=", common);
}

